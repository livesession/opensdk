/// Thread one generated request through the override hooks: mutate, execute,
/// transform, recover, then print. Printing happens ONLY here (via the trait),
/// so overrides fully control the CLI's output.
pub async fn run_request<O: CliOverrides>(
    ctx: &Context,
    o: &O,
    cmd_path: &[String],
    mut req: Request,
) -> ExitCode {
    o.before_request(ctx, cmd_path, &mut req);
    let outcome = match ctx.execute(req).await {
        Ok(value) => o.transform_response(ctx, cmd_path, value),
        Err(err) => Err(err),
    };
    match outcome.or_else(|err| o.recover_error(ctx, cmd_path, err)) {
        Ok(value) => {
            o.print_success(cmd_path, &value);
            ExitCode::SUCCESS
        }
        Err(err) => o.print_error(cmd_path, &err),
    }
}
